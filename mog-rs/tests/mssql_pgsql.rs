//! Golden tests for the `tests/sql/MSSQL-To-PGSQL-Table.mog` conversion script,
//! run against its `.sql` fixtures. Expected outputs live beside the fixtures as
//! `*.pgsql`. EOL is normalized to LF before comparison so git's autocrlf handling
//! can't make these flaky.

use std::collections::BTreeMap;
use std::path::PathBuf;

use mog::{execute_at, parse_mog, parse_mog_with_defines};

// The converter recipe, its `.sql`/`.pgsql` fixtures, and the broader schema
// inputs all live in `tests/sql/`.
fn fixture(rel: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/sql")
        .join(rel)
}

/// The tests/sql dir, used as the base dir so `run_mog` can resolve sibling scripts.
fn fixture_dir() -> PathBuf {
    fixture("")
}

fn read(rel: &str) -> String {
    std::fs::read_to_string(fixture(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}"))
}

fn lf(s: &str) -> String {
    s.replace("\r\n", "\n").replace('\r', "\n")
}

fn convert(input_rel: &str) -> String {
    let script = read("MSSQL-To-PGSQL-Table.mog");
    let input = read(input_rel);
    let mog = parse_mog(&script).expect("parse MSSQL-To-PGSQL-Table.mog");
    execute_at(&mog, &input, Some(fixture_dir().as_path())).expect("execute conversion")
}

#[test]
fn golden_shopdemo_schema() {
    let out = convert("MSSQL-To-PGSQL-Table.TestInput.sql");
    let expected = read("MSSQL-To-PGSQL-Table.TestExpectedOutput.pgsql");
    assert_eq!(
        lf(&out),
        lf(&expected),
        "ShopDemo schema conversion drifted"
    );
}

