
  CREATE TABLE "SYSTEM"."ORA2DD_ORDERS" 
   (	"ORDER_ID" NUMBER(38,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"LEGACY_ID" NUMBER(38,0) DEFAULT "SYSTEM"."ORA2DD_ORDERS_SEQ"."NEXTVAL" NOT NULL ENABLE, 
	"CUSTOMER_NO" NUMBER(10,0) NOT NULL ENABLE, 
	"SKU" VARCHAR2(64) NOT NULL ENABLE, 
	"DESCRIPTION" VARCHAR2(4000), 
	"NOTES" CLOB, 
	"QTY" NUMBER(9,0) DEFAULT 1 NOT NULL ENABLE, 
	"UNIT_PRICE" NUMBER(18,4) NOT NULL ENABLE, 
	"DISCOUNT_PCT" NUMBER(5,2) DEFAULT 0, 
	"LINE_TOTAL" NUMBER(20,4) GENERATED ALWAYS AS ("QTY"*"UNIT_PRICE"*(1-"DISCOUNT_PCT"/100)) VIRTUAL , 
	"IS_ACTIVE" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE, 
	"STATUS" VARCHAR2(20) DEFAULT 'NEW' NOT NULL ENABLE, 
	"PAYLOAD" RAW(2000), 
	"DOC_BLOB" BLOB, 
	"CREATED_AT" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"UPDATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP, 
	"EVENT_TS" TIMESTAMP (6) WITH TIME ZONE, 
	 CONSTRAINT "ORA2DD_ORDERS_QTY_CK" CHECK (qty > 0) ENABLE, 
	 CONSTRAINT "ORA2DD_ORDERS_DISC_CK" CHECK (discount_pct >= 0 AND discount_pct <= 100) ENABLE, 
	 CONSTRAINT "ORA2DD_ORDERS_PK" PRIMARY KEY ("ORDER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "ORA2DD_ORDERS_UQ" UNIQUE ("SKU", "CUSTOMER_NO")
  USING INDEX  ENABLE
   ) 