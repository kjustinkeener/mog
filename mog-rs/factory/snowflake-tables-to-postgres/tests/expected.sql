CREATE TABLE CUSTOMERS (
	ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	NAME VARCHAR(200),
	EMAIL VARCHAR(255),
	BALANCE NUMERIC(18,2),
	ATTRS JSONB,
	CREATED_AT TIMESTAMP,
	UPDATED_AT TIMESTAMPTZ,
	REGION VARCHAR(50)
)
